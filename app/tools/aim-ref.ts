// Writes src/stats/aim-ref.ts, each gun's max speed, from the decoded weapons vdata. The spray reference
// is recoil.ts (tools/recoil.ts), built from the demos' own shot records.
// Usage (from app/): pnpm aim-ref <weapons_out>
import { createHash } from "node:crypto";
import { readFileSync } from "node:fs";
import path from "node:path";
import { writeOutput } from "./outputs";

const [vdataPath] = process.argv.slice(2);
const vdataBytes = readFileSync(vdataPath);
const sha = (b: Buffer) => createHash("sha256").update(b).digest("hex");
const vdata = vdataBytes.toString("utf8");

// m_flMaxSpeed per weapon block. "\tname =" opens a top-level block in the KV3 text; only the
// weapon_* blocks count (melee and item blocks sit between them).
const speed: Record<string, [number, number]> = {};
let name: string | null = null;
for (const line of vdata.split(/\r?\n/)) {
  const m = /^\t([a-z0-9_]+) =\s*$/.exec(line);
  if (m) name = m[1].startsWith("weapon_") ? m[1].slice("weapon_".length) : null;
  const s = /^\t\tm_flMaxSpeed = (?:\[ ([\d.]+), ([\d.]+) \]|([\d.]+))/.exec(line);
  if (s && name) speed[name] = s[3] ? [Number(s[3]), Number(s[3])] : [Number(s[1]), Number(s[2])];
}
const GUNS = ["glock", "hkp2000", "usp_silencer", "p250", "elite", "fiveseven", "tec9", "cz75a", "deagle", "revolver",
  "mac10", "mp9", "mp7", "mp5sd", "ump45", "p90", "bizon", "nova", "xm1014", "sawedoff", "mag7", "m249", "negev",
  "galilar", "famas", "ak47", "m4a1", "m4a1_silencer", "sg556", "aug", "awp", "ssg08", "g3sg1", "scar20"];
const SCOPED = new Set(["awp", "ssg08", "g3sg1", "scar20", "aug", "sg556"]);

let out = `// Generated by tools/aim-ref.ts; do not edit by hand. Regenerate when the source changes, and
// bump DERIVE_VERSION (facts.ts), because spray and counter-strafe facts depend on these numbers.
//
// MAX_SPEED: m_flMaxSpeed from the game's scripts/weapons.vdata_c, decoded to KV3 text
//   (%TEMP%\\pr220\\loc\\weapons_out, sha256 ${sha(vdataBytes)}). Units/s; the second value
//   is the scoped speed and is listed only for weapons with a scope.

/** Max speed, units/s: [unscoped, scoped] or [unscoped]. */
export const MAX_SPEED: Record<string, readonly number[]> = {\n`;
for (const g of GUNS) {
  const s = speed[g];
  if (!s) throw new Error(`no m_flMaxSpeed for ${g}`);
  out += `  ${g}: [${SCOPED.has(g) && s[1] !== s[0] ? `${s[0]}, ${s[1]}` : s[0]}],\n`;
}
out += "};\n";
const AIM_REF = path.resolve(import.meta.dirname, "../src/stats/aim-ref.ts");
// read from the game's weapon data, no pack data
writeOutput(AIM_REF, out, { private: false, what: "aim-ref.ts", inRepo: AIM_REF });
console.log("wrote src/stats/aim-ref.ts", out.length, "bytes");
