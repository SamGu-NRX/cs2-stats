// Writes src/stats/aim-ref.ts from the recoil asset and the decoded weapons vdata.
// Usage (from app/): pnpm aim-ref <recoil_patterns.json> <weapons_out>
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const [assetPath, vdataPath] = process.argv.slice(2);
const assetBytes = readFileSync(assetPath);
const vdataBytes = readFileSync(vdataPath);
const sha = (b: Buffer) => createHash("sha256").update(b).digest("hex");
const asset = JSON.parse(assetBytes.toString("utf8"));
const vdata = vdataBytes.toString("utf8");

// m_flMaxSpeed per weapon block. "\tname =" opens a top-level block in the KV3 text; only the
// weapon_* blocks count (melee and item blocks sit between them).
const speed: Record<string, [number, number]> = {};
let name: string | null = null;
for (const line of vdata.split(/\r?\n/)) {
  const m = /^\t([a-z0-9_]+) =\s*$/.exec(line);
  if (m) name = m[1].startsWith("weapon_") ? m[1].slice("weapon_".length) : null;
  const s = /^\t\tm_flMaxSpeed = (?:\[ ([\d.]+), ([\d.]+) \]|([\d.]+))/.exec(line);
  if (s && name) speed[name] = s[3] ? [Number(s[3]), Number(s[3])] : [Number(s[1]), Number(s[2])];
}
const GUNS = ["glock", "hkp2000", "usp_silencer", "p250", "elite", "fiveseven", "tec9", "cz75a", "deagle", "revolver",
  "mac10", "mp9", "mp7", "mp5sd", "ump45", "p90", "bizon", "nova", "xm1014", "sawedoff", "mag7", "m249", "negev",
  "galilar", "famas", "ak47", "m4a1", "m4a1_silencer", "sg556", "aug", "awp", "ssg08", "g3sg1", "scar20"];
const SCOPED = new Set(["awp", "ssg08", "g3sg1", "scar20", "aug", "sg556"]);
const r4 = (x: number) => Math.round(x * 1e4) / 1e4;

let out = `// Generated by tools/aim-ref.ts; do not edit by hand. Regenerate when either source changes,
// and bump DERIVE_VERSION (facts.ts), because spray and counter-strafe facts depend on these numbers.
//
// MAX_SPEED: m_flMaxSpeed from the game's scripts/weapons.vdata_c, decoded to KV3 text
//   (%TEMP%\\pr220\\loc\\weapons_out, sha256 ${sha(vdataBytes)}, the same file
//   recoil_patterns.json names in input.vdataSha256). Units/s; the second value is the scoped speed
//   and is listed only for weapons with a scope.
// RECOIL: cs2-stats-data/derived/recoil_patterns.json (sha256 ${sha(assetBytes)}, status
//   "${asset.status}", scoringApproved ${asset.scoringApproved}, target build ${asset.targetBuild}). Per weapon: cycle
//   time (s) and magazine size, and for bullets 1..supportedThroughBullet the median pro view
//   compensation relative to the first shot, [pitch, yaw, pitchQ25, pitchQ75, yawQ25, yawQ75] in
//   degrees, pitch positive down. Weapons with supportedThroughBullet 0 keep their cycle time and
//   magazine (the spray segmentation needs them) and an empty path.

/** Max speed, units/s: [unscoped, scoped] or [unscoped]. */
export const MAX_SPEED: Record<string, readonly number[]> = {\n`;
for (const g of GUNS) {
  const s = speed[g];
  if (!s) throw new Error(`no m_flMaxSpeed for ${g}`);
  out += `  ${g}: [${SCOPED.has(g) && s[1] !== s[0] ? `${s[0]}, ${s[1]}` : s[0]}],\n`;
}
out += `};

export interface RecoilRef {
  cycle: number;
  mag: number;
  /** index 0 is bullet 1 */
  path: readonly (readonly number[])[];
}

export const RECOIL: Record<string, RecoilRef> = {\n`;
for (const [w, d] of Object.entries<any>(asset.weapons)) {
  const n = d.supportedThroughBullet as number;
  const rows = d.ideal.slice(0, n).map((b: any, i: number) => {
    const t = d.tolerance[i];
    if (b.bullet !== i + 1 || t.bullet !== i + 1) throw new Error(`${w}: bullet order`);
    return `[${[b.pitch, b.yaw, t.pitchQ25, t.pitchQ75, t.yawQ25, t.yawQ75].map(r4).join(", ")}]`;
  });
  out += `  ${w}: { cycle: ${d.cycleTime}, mag: ${d.magazineSize}, path: [${rows.length ? "\n    " + rows.join(",\n    ") + ",\n  " : ""}] },\n`;
}
out += "};\n";
writeFileSync("src/stats/aim-ref.ts", out);
console.log("wrote src/stats/aim-ref.ts", out.length, "bytes");
