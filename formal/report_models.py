"""Render reviewed TLC counts and compact, concrete state-difference traces."""
from pathlib import Path
import hashlib
import json
import re

ROOT = Path(__file__).resolve().parent


def main():
    results = json.loads((ROOT / "results" / "protocol-summary.json").read_text())
    required = {p.stem for prefix in ("Publish","MapGate","Plugin","Pipeline")
                for p in ROOT.glob(prefix + "*.cfg")}
    if missing := required - results.keys():
        raise ValueError("missing configurations: " + ", ".join(sorted(missing)))
    lines = ["# Protocol model-check results", "",
             "Generated by `python -I formal/report_models.py`. See [AUDIT.md](AUDIT.md) for code mappings, fixes, assumptions and bounds. "
             "PASS exhausts the configured state space; counterexample counts stop at the first violation. "
             "All new checks use TLC 2.19 from the checksum-pinned TLA+ 1.7.4 jar, Java 21, one worker and the runner's `--while-gaming` option.", "",
             "| Configuration (exact bounds) | Result / property | Generated | Distinct |", "| --- | --- | ---: | ---: |"]
    witnesses = ["# Concrete TLC witnesses", "",
                 "Generated state differences from the retained TLC logs, with unchanged fields omitted. "
                 "These are actual TLC traces, not illustrative schedules. Full logs are regenerated under ignored `results/`. "
                 "The initial state is defined by each linked config and its module. "
                 "`0` is the old version, `1`/`2` are fresh extraction nonces; `other` can be `damages.parquet`. "
                 "The `match` unit includes the rating helper's `player_rounds` layout requirement. "
                 "Code locations and witness interpretation are in [AUDIT.md](AUDIT.md).", "",
                 "Writer `pc`: 0 not started; 1 mkdir; 2 first table; 3 remaining tables; 4 schema reads passed; "
                 "5 manifest listing captured; 6 COMPLETE written; 7 folder renamed; 8 pointer staged; 9 CURRENT replaced; "
                 "11 RETIRED unlinked / finished; -1 failed. `ppc`/`cached`/`pending` are each pruner's independent state.", ""]
    for name, result in sorted(results.items()):
        config = ROOT / (name + ".cfg")
        module = next(m for m in ("Capture","Calls","Publish","MapGate","Plugin","Pipeline") if name.startswith(m))
        for key, path in (("model_sha256",ROOT / (module + ".tla")),("config_sha256",config)):
            if result.get(key) != hashlib.sha256(path.read_bytes()).hexdigest():
                raise ValueError(f"stale or unbound result: rerun {name}")
        if result["result"] != result["expected"]:
            raise ValueError(f"unexpected result: {name}")
        label = result["result"] + (" / " + result["property"] if "property" in result else "")
        lines.append(f"| [{name}]({name}.cfg) | {label} | {result['generated']:,} | {result['distinct']:,} |")
        if result["result"] != "COUNTEREXAMPLE":
            continue
        log = (ROOT / "results" / (name + ".log")).read_text(encoding="utf-8")
        witnesses += ["## " + name, "", f"Violated `{result['property']}`. [Bounds]({name}.cfg).", "", "```text"]
        blocks = re.split(r"(?m)^State (\d+): ([^\n]+)\n", log)
        previous = {}
        for i in range(1, len(blocks), 3):
            number, action, body = blocks[i:i+3]
            state = re.search(r"s = \[ (.*?) \]\n", body, re.S)
            if not state:
                witnesses.append(f"{number}. {action.strip()}")
                continue
            values = dict((m.group(1), " ".join(m.group(2).split())) for m in
                          re.finditer(r"(?:^|,\n  )(\w+) \|->\s*(.*?)(?=,\n  \w+ \|->|\Z)", state.group(1), re.S))
            changes = {k:v for k,v in values.items() if previous.get(k) != v}
            if number == "1":
                chosen = {k:v for k,v in values.items() if k in {"loc","current","marker","pc","live","named","gate","awaiting","map","oldMarker","oldData","valid"}}
                witnesses.append("1. Initial: " + "; ".join(f"{k}={v}" for k,v in chosen.items()))
            else:
                hint = "" if action.startswith("<Next ") else action.lstrip("<").split(" line ")[0] + ": "
                witnesses.append(number + ". " + hint + "; ".join(f"{k}={v}" for k,v in changes.items()))
            previous = values
        back = re.search(r"Back to state (\d+).*",log)
        if back:
            witnesses.append(back.group(0))
        if "Stuttering" in log:
            witnesses.append("Then stutter forever (no further state changes).")
        witnesses += ["```", ""]
    (ROOT / "RESULTS.md").write_text("\n".join(lines) + "\n", encoding="utf-8")
    (ROOT / "WITNESSES.md").write_text("\n".join(witnesses), encoding="utf-8")


if __name__ == "__main__":
    main()
